package bicep

import (
	"fmt"
	"sort"
	"strings"
)

const header = "// Generated by x-foundry. Regenerate with `xfoundry generate` instead of editing this file.\n"

func (g *gen) tagsVar() string {
	merged := map[string]string{}
	for k, v := range g.n.Tags {
		merged[k] = v
	}
	merged["x-foundry-env"] = g.n.Environment
	return "var tags = " + tagsObject(merged) + "\n"
}

func (g *gen) locationParam() string {
	if loc := g.location(); loc != "" {
		return "param location string = " + str(loc) + "\n"
	}
	return "param location string\n"
}

func (g *gen) mainBicep() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("targetScope = 'subscription'\n\n")
	b.WriteString("@minLength(1)\n@maxLength(64)\n@description('Name of the environment. It is used in resource names and tags.')\nparam environmentName string\n\n")
	b.WriteString("@description('Primary location for all resources.')\n" + g.locationParam() + "\n")
	b.WriteString(g.tagsVar() + "\n")
	fmt.Fprintf(&b, "resource rg 'Microsoft.Resources/resourceGroups@2024-03-01' = {\n  name: %s\n  location: location\n  tags: union(tags, { 'azd-env-name': environmentName, 'x-foundry-id': 'resource-group' })\n}\n\n", g.resourceGroupName())
	b.WriteString("module resources 'resources.bicep' = {\n  name: 'resources'\n  scope: rg\n  params: {\n    environmentName: environmentName\n    location: location\n  }\n}\n\n")
	b.WriteString("output AZURE_RESOURCE_GROUP string = rg.name\n")
	for _, o := range g.outputs {
		fmt.Fprintf(&b, "output %s string = resources.outputs.%s\n", o[0], o[0])
	}
	return b.String()
}

func (g *gen) resourcesBicep() string {
	body := g.body.String()
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("param environmentName string\nparam location string\n\n")
	b.WriteString(g.tagsVar())
	b.WriteString("var token = toLower(uniqueString(subscription().id, environmentName, location))\n")
	fmt.Fprintf(&b, "var base = %s\n", str(g.prefix()))
	if strings.Contains(body, "baseCompact") {
		b.WriteString("var baseCompact = replace(base, '-', '')\n")
	}
	b.WriteString("\n")
	b.WriteString(body)
	for _, o := range g.outputs {
		fmt.Fprintf(&b, "output %s string = %s\n", o[0], o[1])
	}
	return b.String()
}

