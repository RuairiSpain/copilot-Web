#!/usr/bin/env bash
# One-command deploy of the Teams voice agent MVP.
#
#   ./deploy.sh --name tvm --location westeurope                       # infrastructure, then stop for Teams admin
#   ./deploy.sh --name tvm --location westeurope --resource-account-id <guid> [--phone +353...] [--lockdown]
#
# Safe to re-run. Needs: az (logged in, Owner or Contributor + User Access Administrator on the
# subscription, and permission to create Entra app registrations), python3 (3.10+).
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd .. && pwd)"

NAME=tvm LOCATION=westeurope ACS_DATA_LOCATION=Europe SUBSCRIPTION="" RA_ID="" PHONE="" LOCKDOWN=false AGENT=teams-voice-agent UPDATE_AGENT=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --location) LOCATION="$2"; shift 2 ;;
    --acs-data-location) ACS_DATA_LOCATION="$2"; shift 2 ;;
    --subscription) SUBSCRIPTION="$2"; shift 2 ;;
    --resource-account-id) RA_ID="$2"; shift 2 ;;
    --phone) PHONE="$2"; shift 2 ;;
    --agent-name) AGENT="$2"; shift 2 ;;
    --lockdown) LOCKDOWN=true; shift ;;
    --update-agent) UPDATE_AGENT="--update-agent"; shift ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

log()  { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
command -v az >/dev/null || { echo "Azure CLI (az) is required" >&2; exit 1; }
command -v python3 >/dev/null || { echo "python3 is required" >&2; exit 1; }

[[ -n "$SUBSCRIPTION" ]] && az account set --subscription "$SUBSCRIPTION"
az account show >/dev/null 2>&1 || az login >/dev/null
TENANT_ID="$(az account show --query tenantId -o tsv)"
OPERATOR_OID="$(az ad signed-in-user show --query id -o tsv)"
RG="rg-$NAME"

log "Registering resource providers"
for p in Microsoft.CognitiveServices Microsoft.Communication Microsoft.BotService Microsoft.EventGrid Microsoft.Network; do
  az provider register --namespace "$p" --wait >/dev/null
done

log "Resource group $RG"
az group create --name "$RG" --location "$LOCATION" >/dev/null

log "Entra app registration (single tenant)"
APP_NAME="$NAME-teams-voice"
APP_ID="$(az ad app list --filter "displayName eq '$APP_NAME'" --query "[0].appId" -o tsv)"
if [[ -z "$APP_ID" ]]; then
  APP_ID="$(az ad app create --display-name "$APP_NAME" --sign-in-audience AzureADMyOrg --query appId -o tsv)"
  az ad sp create --id "$APP_ID" >/dev/null
fi

deploy_infra() {  # $1 = Enabled|Disabled for the Foundry public endpoint
  az deployment group create --resource-group "$RG" --name teams-voice --template-file main.bicep \
    --parameters prefix="$NAME" location="$LOCATION" acsDataLocation="$ACS_DATA_LOCATION" \
                 botAppId="$APP_ID" operatorPrincipalId="$OPERATOR_OID" foundryPublicNetworkAccess="$1" >/dev/null
}
out() { az deployment group show --resource-group "$RG" --name teams-voice --query "properties.outputs.$1.value" -o tsv; }

log "Deploying infrastructure (Bicep)"
deploy_infra Enabled
FOUNDRY_ENDPOINT="$(out foundryProjectEndpoint)"; ACS_NAME="$(out acsName)"; ACS_ID="$(out acsId)"
ACS_HOST="$(out acsHost)"; ACS_IMMUTABLE_ID="$(out acsImmutableId)"; CONNECTION="$(out connectionName)"

mkdir -p out
cat > out/teams-admin.ps1 <<PS
# Run as a Teams administrator (MicrosoftTeams PowerShell module). Generated by deploy.sh.
\$AppId = '$APP_ID'
\$AcsImmutableId = '$ACS_IMMUTABLE_ID'
\$Upn = 'teams-voice-agent@EDIT-YOUR-DOMAIN.com'   # EDIT: UPN for the new resource account
Connect-MicrosoftTeams
New-CsOnlineApplicationInstance -UserPrincipalName \$Upn -ApplicationId \$AppId -DisplayName 'Teams voice agent'
Start-Sleep -Seconds 60   # directory propagation
\$ra = Get-CsOnlineApplicationInstance -Identity \$Upn
Set-CsOnlineApplicationInstance -Identity \$ra.ObjectId -ApplicationId \$AppId -AcsResourceId \$AcsImmutableId -DisplayName 'Teams voice agent'
Sync-CsOnlineApplicationInstance -ObjectId \$ra.ObjectId -ApplicationId \$AppId -AcsResourceId \$AcsImmutableId
Write-Host "Resource account ObjectId (pass to deploy.sh --resource-account-id): \$(\$ra.ObjectId)"
# Then, in the admin centers (not scriptable here):
#   1. Microsoft 365 admin center: assign the 'Microsoft Teams Phone Resource Account' license to \$Upn.
#   2. Teams admin center: assign a Service number (VoiceApplicationAssignment) to the resource account.
PS

if [[ -z "$RA_ID" ]]; then
  log "Infrastructure is ready. Next: a Teams admin creates the resource account."
  echo "  1. Run infra/out/teams-admin.ps1 (edit the UPN first), then license it and assign a service number."
  echo "  2. Re-run this script with: --name $NAME --location $LOCATION --resource-account-id <ObjectId> [--phone <number>] [--lockdown]"
  exit 0
fi

log "Python CLI"
[[ -d "$ROOT/.venv" ]] || python3 -m venv "$ROOT/.venv"
"$ROOT/.venv/bin/python" -m pip install -q -e "$ROOT"
CLI="$ROOT/.venv/bin/teams-voice"

export FOUNDRY_PROJECT_ENDPOINT="$FOUNDRY_ENDPOINT" VOICE_AGENT_NAME="$AGENT" ACS_CONNECTION_NAME="$CONNECTION"
export RESOURCE_ACCOUNT_OBJECT_ID="$RA_ID" TEAMS_PHONE_NUMBER="$PHONE"

log "Creating voice agent and Teams telephony binding (retrying while the role assignment propagates)"
SETUP_JSON=""
for attempt in 1 2 3 4 5 6; do
  if SETUP_JSON="$("$CLI" setup $UPDATE_AGENT)"; then break; fi
  [[ $attempt -eq 6 ]] && { echo "setup failed; see README, Troubleshooting" >&2; exit 1; }
  sleep 20
done
INCOMING_URL="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1])["incoming_call_url"])' "$SETUP_JSON")"
echo "$SETUP_JSON"

log "Event Grid: route ACS IncomingCall events to the Foundry binding"
TOPIC="$NAME-acs-events"
az eventgrid system-topic show -g "$RG" -n "$TOPIC" >/dev/null 2>&1 || \
  az eventgrid system-topic create -g "$RG" -n "$TOPIC" --location global --source "$ACS_ID" \
    --topic-type microsoft.communication.communicationservices >/dev/null
if ! az eventgrid system-topic event-subscription show -g "$RG" --system-topic-name "$TOPIC" -n incoming-call >/dev/null 2>&1; then
  az eventgrid system-topic event-subscription create -g "$RG" --system-topic-name "$TOPIC" -n incoming-call \
    --endpoint-type webhook --endpoint "$INCOMING_URL" --included-event-types Microsoft.Communication.IncomingCall >/dev/null \
    || warn "Event subscription failed. In the Foundry portal use Channels > Phone numbers > Microsoft Teams > Automatic configuration instead."
fi

log "ACS server consent for the resource account"
ACS_ACCESS_KEY="$(az rest --method post --url "https://management.azure.com${ACS_ID}/listKeys?api-version=2023-04-01" --query primaryKey -o tsv)" \
  "$CLI" consent --acs-host "$ACS_HOST" --teams-tenant-id "$TENANT_ID" --resource-account-id "$RA_ID" \
  || warn "Consent call failed. Calls may return Busy until it succeeds (see README)."

cat > "$ROOT/.env" <<ENV
FOUNDRY_PROJECT_ENDPOINT=$FOUNDRY_ENDPOINT
VOICE_AGENT_NAME=$AGENT
ACS_CONNECTION_NAME=$CONNECTION
RESOURCE_ACCOUNT_OBJECT_ID=$RA_ID
TEAMS_PHONE_NUMBER=$PHONE
ENV

if [[ "$LOCKDOWN" == true ]]; then
  log "Disabling the Foundry public endpoint"
  deploy_infra Disabled
  warn "Foundry is now private. Run the CLI from inside the VNet. Test an incoming call now; if it fails, re-run without --lockdown."
fi

log "Done. Dial the resource account number (or add it to a Teams meeting as a phone participant) to test."
echo "  Foundry project: $FOUNDRY_ENDPOINT"
echo "  Watch calls:     set -a; . $ROOT/.env; set +a; $CLI watch"
